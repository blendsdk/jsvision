import { defineCatalog, plural } from '@jsvision/i18n';
import type { Catalog } from '@jsvision/i18n';

import { CODE_EDITOR_ACCELERATOR_MANIFEST, CODE_EDITOR_ENGLISH_CATALOG, type CodeEditorMessageMap } from './catalog.js';

/** Builds one complete Code Editor catalog from an exhaustively typed locale message map. */
function codeEditorCatalog(locale: string, messages: CodeEditorMessageMap): Catalog {
  return defineCatalog({ schema: 1, locale, messages }, { acceleratorManifest: CODE_EDITOR_ACCELERATOR_MANIFEST });
}

