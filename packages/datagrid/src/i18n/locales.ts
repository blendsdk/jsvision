import { DATAGRID_ACCELERATOR_MANIFEST, DATAGRID_ENGLISH_CATALOG } from './catalog.js';

/** Complete Datagrid message map required from every non-English official locale. */
type DatagridMessages = typeof DATAGRID_ENGLISH_CATALOG.messages;

/** Build one complete Datagrid catalog from reviewed translations. */
function datagridCatalog(locale: string, messages: DatagridMessages): Catalog {
  return defineCatalog(
    {
      schema: 1,
      locale,
      messages,
    },
    {
      acceleratorManifest: DATAGRID_ACCELERATOR_MANIFEST,
      placeholderManifest: {
        'datagrid.personalize.visible-count': ['visible', 'total'],
        'datagrid.personalize.confirm.overwrite': ['name'],
        'datagrid.personalize.confirm.delete': ['name'],
        'datagrid.validation.row-trapped': ['message'],
      },
    },
  );
}

