const MONTH_KEYS = [
  'january',
  'february',
  'march',
  'april',
  'may',
  'june',
  'july',
  'august',
  'september',
  'october',
  'november',
  'december',
] as const;
const WEEKDAY_KEYS = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'] as const;

/** Complete calendar and interface values used to construct one UI catalog. */
interface UiTranslation {
  readonly messages: Readonly<Record<string, Message>>;
  readonly months: readonly [
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
    string,
  ];
  readonly weekdays2: readonly [string, string, string, string, string, string, string];
  readonly weekdays3: readonly [string, string, string, string, string, string, string];
}

/** Build one complete UI catalog from translated values and canonical English keys. */
function uiCatalog(locale: string, translation: UiTranslation): Catalog {
  const calendarMessages: Record<string, Message> = {};
  MONTH_KEYS.forEach((month, index) => {
    calendarMessages[`ui.calendar.month.${month}`] = translation.months[index];
  });
  WEEKDAY_KEYS.forEach((weekday, index) => {
    calendarMessages[`ui.calendar.weekday.${weekday}.short2`] = translation.weekdays2[index];
    calendarMessages[`ui.calendar.weekday.${weekday}.short3`] = translation.weekdays3[index];
  });
  return defineCatalog(
    {
      schema: 1,
      locale,
      messages: {
        ...UI_ENGLISH_CATALOG.messages,
        ...translation.messages,
        ...calendarMessages,
      },
    },
    {
      acceleratorManifest: UI_ACCELERATOR_MANIFEST,
      placeholderManifest: {
        'ui.editor.save-modified': ['name'],
        'ui.editor.read-error': ['name'],
        'ui.editor.write-error': ['name'],
        'ui.editor.create-error': ['name'],
      },
    },
  );
}

